"""tables15.py -> native15/layer/retail_tables.S: the 1.5 XBE's sections to load (with their CRCs), what 1.5's start-up
initialisers leave in memory (native15/init_delta.json from emuinit15.py), and the code pointers in 1.5's data to re-aim
at our functions: each of 1.0's (generated/retail_tables.template.S) whose slot datalign15.py pairs with a 1.5 slot that
points at a function with the same whole body (address fields aside) as the 1.0 one. A slot whose 1.5 function changed
keeps 1.5's pointer (that function runs as 1.5's own code)."""
import re, json, struct, sys, zlib, csv, collections
sys.path.insert(0, '/home/claude/v15')
from fmap_lib import load, mask
from xmap15_lib import r10, r15
import datamap15
D15, S15 = load('/home/claude/v15/default_v15.xbe')
T = open('/home/claude/native/layer/retail_tables.S').read()      # (the fix-ups as gen.py and fix_resolve.py last wrote them)
slots = {int(k, 16): v for k, v in json.load(open('/home/claude/v15/slots15.json'))['slots'].items()}
size = {int(r[0], 16): int(r[1]) for r in csv.reader(open('/home/claude/h2decomp_src/halo2-decompiled-main/config/functions.csv'))
        if r and r[0][:1] in '0123456789abcdef' and r[1].isdigit()}
names = [m.group(1) for m in re.finditer(r'^LS\d+: \.asciz "(.*)"$', T, re.M)]
o = ['/* generated by tables15.py from the 1.5 title update\'s XBE: what to load, what the start-up initialisers write, which code pointers to re-aim */',
     '.section .rdata,"dr"', '.balign 4', '.globl _h2n_sections', '_h2n_sections:']
for i, n in enumerate(names):
    s = [x for x in S15 if x['name'] == n][0]
    o.append('  .long LS%d, 0x%x, 0x%x, 0x%x, 0x%x' % (i, s['va'], s['vs'], s['rs'], zlib.crc32(D15[s['raw']:s['raw'] + s['rs']]) & 0xffffffff))
o.append('  .long 0,0,0,0,0')
for i, n in enumerate(names): o.append('LS%d: .asciz "%s"' % (i, n))
o += ['.balign 4', '.globl _h2n_delta', '_h2n_delta:']
delta = json.load(open('/home/claude/native15/init_delta.json')); total = 0
for a, hexb in delta['runs']:
    b = bytes.fromhex(hexb); total += len(b)
    o.append('  .long %#x, %d\n  .byte %s\n  .balign 4' % (a, len(b), ','.join(str(v) for v in b)))
o += ['  .long 0,0', '.balign 4', '.globl _h2n_fixups', '_h2n_fixups:']
fx = [(int(a, 16), int(b, 16), n) for a, b, n in re.findall(r'^\s*\.long 0x([0-9a-f]+), 0x([0-9a-f]+), "(.*)"$', T, re.M)]
st = collections.Counter(); seen = set()
from strict_lib import strict as _strict
def same_body(t10, t15):
    n = size.get(t10)
    if not n: return False
    return _strict(t10, t15, n)                # (s10r) instruction for instruction: the mask let changed numbers through
# the 1.5 place of a slot: from its table's own start where same code names that start (a vtable a constructor stores:
# the class is what it is, while tiny methods whose bytes are alike make a pairing by contents swap whole tables -
# 1.0's 0x4138c8 / 0x4138cc / 0x4138d4 listener vtables), else the word pairing, else the data map
import re as _re, bisect as _bisect
_V = {int(k, 16): v for k, v in json.load(open('/home/claude/v15/map15.json'))['data'].items()}
_t10 = {m.group(1): int(m.group(2), 16) for m in _re.finditer(r'^\s*"?(.*?)"?\s*=\s*0x([0-9a-f]+)', open('/home/claude/native/layer/retail_syms.S').read(), _re.M)}
_t15 = {m.group(1): int(m.group(2), 16) for m in _re.finditer(r'^\s*"?(.*?)"?\s*=\s*0x([0-9a-f]+)', open('/home/claude/native15/layer/retail_syms.S').read(), _re.M)}
_bases = {}
for k, a in _t10.items():
    if k in _t15 and a in _V: _bases[a] = _t15[k]
# (s10s) and a table found by its own contents (vt15.py)
import os as _os
if _os.path.exists('/home/claude/v15/vt15.json'):
    for _k, _v in json.load(open('/home/claude/v15/vt15.json')).items(): _bases[int(_k, 16)] = _v[0]
_bk = sorted(_bases)
def slot15(s10):
    i = _bisect.bisect_right(_bk, s10) - 1
    if i >= 0 and s10 - _bk[i] < 0x80: return _bases[_bk[i]] + (s10 - _bk[i]), 'table start'
    if s10 in slots: return slots[s10], 'paired word'
    return datamap15.map_data(s10)[0], 'data map'
for s10, t10, n in fx:
    s15, how = slot15(s10); st['slot by ' + how] += 1
    w = r15(s15, 4)
    if not w: st['no slot'] += 1; continue
    t15 = struct.unpack('<I', w)[0]
    if not same_body(t10, t15): st['1.5 function changed: stays 1.5\'s'] += 1; continue
    if s15 in seen: continue
    seen.add(s15)
    o.append('  .long 0x%x, 0x%x, "%s"' % (s15, t15, n)); st['re-aimed'] += 1
o.append('  .long 0,0,0')
open('/home/claude/native15/layer/retail_tables.S', 'w').write('\n'.join(o) + '\n')
print('sections', len(names), 'initialiser runs', len(delta['runs']), 'bytes', total, dict(st))
