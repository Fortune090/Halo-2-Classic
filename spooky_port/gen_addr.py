# gen_addr.py: sg_addr.h for the H2Classic port - each address the mod names, for both game versions, picked at run time.
# Game functions, the XBE's library functions and Direct3D's own data are NOT defined: every use of one in the port is
# written by hand (a call by the function's own name with its declared arguments, or the layer's Direct3D).
import re,json,sys
S='/home/claude/uploads_sg/x/Spooky_Ghost_Menu_v2.0.40_R89/source/'
def load(p):
    d={}; order=[]
    for l in open(p):
        m=re.match(r'#define\s+ADDR_(\w+)\s+(\S+)',l)
        if m: d[m.group(1)]=m.group(2); order.append(m.group(1))
    return d,order
a,order=load(S+'addr_v10.h'); b,_=load(S+'addr_v15.h')
out=['/* generated by sgport/gen_addr.py from Spooky Ghost v2.0.40\'s addr_v10.h and addr_v15.h: do not edit */','#ifndef SG_ADDR_H','#define SG_ADDR_H']
skipped=[]
for n in order:
    va=a[n]
    try: v=int(va.rstrip('uU'),16) if va.lower().startswith('0x') else None
    except ValueError: v=None
    if v is None:
        if n in b and b[n]!=va: out.append('/* %s: %s / %s */'%(n,va,b[n]))
        else: out.append('#define ADDR_%s %s'%(n,va))
        continue
    if n not in b: out.append('/* ADDR_%s: v1.0 only (0x%X) */'%(n,v)); skipped.append(n); continue
    w=int(b[n].rstrip('uU'),16)
    if 0x11000<=v<0x411000 or 0x404dd0<=v<0x409000: skipped.append(n); out.append('/* ADDR_%s (0x%X / 0x%X): code or Direct3D\'s own - by hand */'%(n,v,w)); continue
    out.append('#define ADDR_%s SGA(0x%Xu, 0x%Xu)'%(n,v,w))
out.append('#endif')
open(sys.argv[1],'w').write('\n'.join(out)+'\n')
print(len(order),'names;',len(skipped),'left to hand:',' '.join(skipped))
print('only in v15:',[n for n in b if n not in a])
